/**
 * Writes src/Defines/recipes.ts: each fabricator's recipes (the reagents per item), for `lr` Recipe and Required.
 *
 * The amounts come from the game's Stationpedia export (Ryex/StationeersStationpediaExtractor's
 * `stationpedia_export`), which lists every item's recipes with the machine that makes them. It reads
 * <game>/Stationpedia/Stationpedia.json, finding the game as the catalogue tools do (STATIONEERS_DIR, else Steam).
 * A path to a Stationpedia.json given as an argument wins:
 *
 *   node tools/generate-recipes.ts [path/to/Stationpedia.json]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Reagents } from "../src/index.ts";
import { gameDir } from "./game-dir.ts";

/**
 * The machines that answer `lr` Recipe and Required: in the game's code (Assembly-CSharp.dll, read 2026-10-12),
 * lr needs a device implementing IRequireReagent, which only Fabricator and SimpleFabricatorBase do. Their
 * subclasses are these. Any other device raises IncorrectReagentDevice, whatever recipes the export lists for it.
 */
const FABRICATORS = [
	"StructureAutolathe",
	"StructureElectronicsPrinter",
	"StructureHydraulicPipeBender",
	"StructureToolManufactory",
	"StructureSecurityPrinter",
	"StructureOrganicsPrinter",
	"StructureAutomatedOven",
	"StructureAdvancedPackagingMachine",
	"StructureRocketManufactory",
	"StructureTerraformingManufactory",
];

/** A recipe's fields that aren't reagent amounts. */
const NOT_REAGENTS = new Set([
	"CreatorPrefabName",
	"TierName",
	"Time",
	"Energy",
	"Temperature",
	"Pressure",
	"RequiredMix",
	"CountTypes",
]);

type ExportRecipe = Record<string, unknown> & { CreatorPrefabName?: string };
type Recipe = { item: number; name: string; reagents: Record<string, number> };

function exportPath(): string {
	const arg = process.argv[2];
	if (arg) return path.resolve(arg);
	const game = gameDir();
	if (game) return path.join(game, "Stationpedia", "Stationpedia.json");
	throw new Error(
		"Can't find the game (not in a Steam library). Set STATIONEERS_DIR to its folder, or give the path to Stationpedia.json.",
	);
}

const file = exportPath();
if (!existsSync(file)) throw new Error(`No Stationpedia export at ${file}`);
const data = JSON.parse(readFileSync(file, "utf8")) as { version?: string };

const recipes = new Map<string, Recipe[]>(FABRICATORS.map((prefab) => [prefab, []]));
const warnings: string[] = [];

// Each recipe sits somewhere below its item's page; the nearest object with a PrefabName is the item.
function walk(node: unknown, item: { PrefabName: string; PrefabHash: number } | undefined): void {
	if (!node || typeof node !== "object") return;
	const record = node as Record<string, unknown>;
	const owner =
		typeof record.PrefabName === "string" && typeof record.PrefabHash === "number"
			? { PrefabName: record.PrefabName, PrefabHash: record.PrefabHash }
			: item;
	if (Array.isArray(record.Recipes) && owner) {
		for (const recipe of record.Recipes as ExportRecipe[]) {
			const list = recipe.CreatorPrefabName ? recipes.get(recipe.CreatorPrefabName) : undefined;
			if (!list) continue;
			if (list.some((r) => r.item === owner.PrefabHash)) {
				warnings.push(`${recipe.CreatorPrefabName}: a second recipe for ${owner.PrefabName} is ignored`);
				continue;
			}
			const reagents: Record<string, number> = {};
			for (const [key, value] of Object.entries(recipe)) {
				if (NOT_REAGENTS.has(key) || typeof value !== "number" || value === 0) continue;
				if (Reagents.getByValue(key as never) === undefined)
					warnings.push(`unknown reagent ${key} (${owner.PrefabName})`);
				reagents[key] = value;
			}
			list.push({ item: owner.PrefabHash, name: owner.PrefabName, reagents });
		}
	}
	for (const value of Object.values(record)) walk(value, owner);
}
walk(data, undefined);

const out = path.resolve(process.cwd(), "src", "Defines", "recipes.ts");
const body = JSON.stringify(Object.fromEntries(recipes), null, "\t");
writeFileSync(
	out,
	`// Generated by tools/generate-recipes.ts from the game's Stationpedia export${data.version ? ` (game ${data.version})` : ""}. Don't edit by hand.

/** One recipe: the item's prefab hash and name, and the reagents it takes (by reagent name). */
export type FabricatorRecipe = {
	readonly item: number;
	readonly name: string;
	readonly reagents: Readonly<Record<string, number>>;
};

/**
 * The machines that answer \`lr\` Recipe and Required (those whose game class implements IRequireReagent), each
 * with its recipes in the export's order. Any other device raises IncorrectReagentDevice.
 */
export const RECIPES: Readonly<Record<string, readonly FabricatorRecipe[]>> = ${body};
`,
);

const total = [...recipes.values()].reduce((sum, list) => sum + list.length, 0);
for (const warning of warnings) console.warn(`warning: ${warning}`);
console.log(`recipes: ${total} for ${recipes.size} fabricators -> ${path.relative(process.cwd(), out)}`);
